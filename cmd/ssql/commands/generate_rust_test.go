// rustFromCommands assembles the Rust program for a command list, the
// way assembleFromCommands assembles SQL.
func rustFromCommands(t *testing.T, funcName string, cmds ...string) string {
	t.Helper()
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	for _, c := range cmds {
		if err := enc.Encode(lib.CodeFragment{Type: "stmt", Command: c}); err != nil {
			t.Fatal(err)
		}
	}
	code, err := assembleRust(&buf, funcName)
	if err != nil {
		t.Fatalf("assembleRust(%v): %v", cmds, err)
	}
	return code
}

// rustFuncBody is the pipeline function's body lines, trimmed.
func rustFuncBody(code string) []string {
	var body []string
	in := false
	for _, ln := range strings.Split(code, "\n") {
		switch {
		case strings.HasPrefix(ln, "pub async fn "):
			in = true
		case in && ln == "}":
			return body
		case in:
			body = append(body, strings.TrimSpace(ln))
		}
	}
	return body
}

// TestGenerateRustProgram pins the whole program for the codelab
// pipeline: the hybrid rendering (builders for the flag stages, the
// translator's SQL text for the expression stage), the imports, the
// session and the sink.
func TestGenerateRustProgram(t *testing.T) {
	code := rustFromCommands(t, "",
		"ssql from employees.csv",
		"ssql where -if status eq active",
		"ssql update -set-expr bonus 'salary * 0.1'",
		"ssql group-by dept -avg salary avg_salary -sum bonus bonus",
		"ssql sort -desc avg_salary",
		"ssql limit 10",
		"ssql to table")
	want := `// Generated by ssql generate rust — runs on Apache DataFusion 55
// Pipeline:
//   ssql from employees.csv
//   ssql where -if status eq active
//   ssql update -set-expr bonus 'salary * 0.1'
//   ssql group-by dept -avg salary avg_salary -sum bonus bonus
//   ssql sort -desc avg_salary
//   ssql limit 10
//   ssql to table

#![allow(unused_imports)]

use datafusion::arrow::datatypes::{DataType, Field, Schema};
use datafusion::error::Result;
use datafusion::functions_aggregate::expr_fn as agg;
use datafusion::functions_window::expr_fn as win;
use datafusion::logical_expr::Operator;
use datafusion::prelude::*;

pub async fn pipeline(ctx: &SessionContext) -> Result<DataFrame> {
    let df = ctx.read_csv("employees.csv", CsvReadOptions::new().has_header(true)).await?;
    let df = df.filter(col("status").eq(lit("active")))?;
    let e1 = df.parse_sql_expr(r#"("salary" * CAST(0.1 AS DOUBLE))"#)?;
    let df = df.with_column("bonus", e1)?;
    let df = df.aggregate(vec![col("dept")], vec![cast(agg::avg(col("salary")), DataType::Float64).alias("avg_salary"), coalesce(vec![agg::sum(col("bonus")), lit(0i64)]).alias("bonus")])?;
    let df = df.sort(vec![col("avg_salary").sort(false, true)])?;
    let df = df.limit(0, Some(10))?;
    Ok(df)
}

#[tokio::main]
async fn main() -> Result<()> {
    let config = SessionConfig::new().set_str("datafusion.catalog.has_header", "true");
    let ctx = SessionContext::new_with_config(config).enable_url_table();
    let df = pipeline(&ctx).await?;
    df.show().await?;
    Ok(())
}
`
	if code != want {
		t.Errorf("program differs\n--- want\n%s\n--- got\n%s", want, code)
	}
}

// TestGenerateRustLayers pins one line per layer kind: what each stage
// becomes, and which forms run as SQL text over a view.
func TestGenerateRustLayers(t *testing.T) {
	cases := []struct {
		name  string
		cmds  []string
		wants []string // substrings of the function body, in order
	}{
		{"expression where is text, bound before the filter",
			[]string{"ssql from e.csv", `ssql where -if-expr 'age > 30 && status == "active"'`},
			[]string{`let e1 = df.parse_sql_expr(r#"(("age" > 30) AND ("status" = 'active'))"#)?;`, `let df = df.filter(e1)?;`}},
		{"or of and groups",
			[]string{"ssql from e.csv", "ssql where -if age gt 30 -if dept eq eng + -if age lt 25"},
			[]string{`let df = df.filter((col("age").gt(lit(30i64)).and(col("dept").eq(lit("eng")))).or(col("age").lt(lit(25i64))))?;`}},
		{"negated condition keeps the translator's text",
			[]string{"ssql from e.csv", "ssql where +if age gt 30"},
			[]string{`parse_sql_expr(r#"NOT COALESCE(("age" > 30), FALSE)"#)`}},
		{"a dotted field name is one column",
			[]string{"ssql from e.csv", "ssql where -if a.b eq x", "ssql include n a.b"},
			[]string{`let df = df.filter(col(Column::from_name("a.b")).eq(lit("x")))?;`, `let df = df.select_columns(&["n", "a.b"])?;`}},
		{"count sink",
			[]string{"ssql from e.csv", "ssql where -if age gt 30", "ssql count"},
			[]string{`let df = df.aggregate(vec![], vec![agg::count(lit(1i64)).alias("count")])?;`}},
		{"aggregate without a builder keeps the registry's text",
			[]string{"ssql from e.csv", "ssql group-by dept -median salary med -count-distinct city cities"},
			[]string{`let e1 = df.parse_sql_expr(r#"`, `AS "med""#)?;`, `agg::count_distinct(col("city")).alias("cities")`}},
		{"ranking window by flag is a builder; a frame aggregate is text",
			[]string{"ssql from e.csv", "ssql window -partition dept -order salary -desc -rank r -sum salary run"},
			[]string{`let df = df.with_column("r", win::rank().partition_by(vec![col("dept")]).order_by(vec![col("salary").sort(false, true)]).build()?)?;`,
				`let e1 = df.parse_sql_expr(r#"SUM("salary") OVER (PARTITION BY "dept" ORDER BY "salary" DESC ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)"#)?;`,
				`let df = df.with_column("run", e1)?;`,
				`let df = df.sort(vec![col("dept").sort(true, false), col("salary").sort(false, true)])?;`}},
		{"join using drops the right key",
			[]string{"ssql from o.csv", "ssql join c.csv -using customer_id -type left", "ssql include customer_id name"},
			[]string{`let s1 = ctx.read_csv("c.csv", CsvReadOptions::new().has_header(true)).await?;`,
				`let df = df.alias("l")?;`, `let s1 = s1.alias("r")?;`,
				`let df = df.join(s1, JoinType::Left, &["customer_id"], &["customer_id"], None)?;`,
				`let df = df.drop_columns(&["r.customer_id"])?;`,
				`let df = df.select_columns(&["customer_id", "name"])?;`}},
		{"projection stages",
			[]string{"ssql from " + rustTestCSV(t), "ssql cast -type age float", "ssql rename -as name who", "ssql exclude status", "ssql distinct", "ssql offset 2"},
			[]string{`let e1 = df.parse_sql_expr(r#"CAST("age" AS DOUBLE)"#)?;`, `let df = df.with_column("age", e1)?;`,
				`let df = df.with_column_renamed("name", "who")?;`, `let df = df.drop_columns(&["status"])?;`,
				`let df = df.distinct()?;`, `let df = df.limit(2, None)?;`}},
		{"parquet source with columns",
			[]string{"ssql from parquet x.parquet -columns a -columns b", "ssql limit 3"},
			[]string{`let df = ctx.read_parquet("x.parquet", ParquetReadOptions::default()).await?;`, `let df = df.select_columns(&["a", "b"])?;`}},
		{"range source is a SQL leaf, the stages after it calls",
			[]string{"ssql from range 5 -start 10", "ssql update -set-expr sq 'n * n'"},
			[]string{`let df = ctx.sql(r#"SELECT value AS "n" FROM generate_series(10, 14, 1)"#).await?;`, `let df = df.with_column("sq", e1)?;`}},
		{"rollup aggregates per grouping set and joins on the set's keys",
			[]string{"ssql from e.csv", "ssql group-by dept city -count n -rollup", "ssql sort dept"},
			[]string{
				`let __s0 = df.clone().aggregate(vec![], vec![agg::count(lit(1i64)).alias("n")])?.alias("__s0")?;`,
				`let __s1 = df.clone().aggregate(vec![col("dept")], vec![agg::count(lit(1i64)).alias("dept_n")])?.alias("__s1")?;`,
				`let __d = df.aggregate(vec![col("dept"), col("city")], vec![agg::count(lit(1i64)).alias("dept_city_n")])?.alias("__d")?;`,
				`let df = __d.join_on(__s0, JoinType::Inner, [lit(true)])?;`,
				`let df = df.join_on(__s1, JoinType::Inner, [binary_expr(col("__d.dept"), Operator::IsNotDistinctFrom, col("__s1.dept"))])?;`,
				`let df = df.select(vec![col("__d.dept").alias("dept"), col("__d.city").alias("city"), col("__s0.n").alias("n"), col("__s1.dept_n").alias("dept_n"), col("__d.dept_city_n").alias("dept_city_n")])?;`,
				`let df = df.sort(vec![col("dept").sort(true, false)])?;`}},
		{"sample sorts by random() and limits, with the stage after it",
			[]string{"ssql from e.csv", "ssql sample 3", "ssql where -if age gt 30"},
			[]string{`let df = df.sort(vec![random().sort(true, false)])?.limit(0, Some(3))?;`, `let df = df.filter(col("age").gt(lit(30i64)))?;`}},
		{"sample -percent filters on random()",
			[]string{"ssql from e.csv", "ssql sample -percent 25"},
			[]string{`let df = df.filter(random().lt(lit(0.25f64)))?;`}},
		{"keyed except is an anti join, deduplicated",
			[]string{"ssql from e.csv", "ssql except -file c.csv -using id"},
			[]string{`let s1 = ctx.read_csv("c.csv"`, `let df = df.join(s1, JoinType::LeftAnti, &["id"], &["id"], None)?;`, `let df = df.distinct()?;`}},
		{"keyed intersect -all is a semi join, duplicates kept",
			[]string{"ssql from e.csv", "ssql intersect -file c.csv -on id cid -all"},
			[]string{`let df = df.join(s1, JoinType::LeftSemi, &["id"], &["cid"], None)?;`}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			body := strings.Join(rustFuncBody(rustFromCommands(t, "", c.cmds...)), "\n")
			pos := 0
			for _, w := range c.wants {
				i := strings.Index(body[pos:], w)
				if i < 0 {
					t.Fatalf("missing (after offset %d):\n  %s\nin body:\n%s", pos, w, body)
				}
				pos += i + len(w)
			}
		})
	}
}

// TestGenerateRustHatchOverAFile pins the DataFrame forms of the layers
// the SQL builds from the columns' names and kinds: unpivot's branch per
// value column and -empty zero's coalesce per numeric column.
func TestGenerateRustHatchOverAFile(t *testing.T) {
	csv := rustTestCSV(t)
	cases := []struct {
		name  string
		cmds  []string
		wants []string
	}{
		{"unpivot is a branch per value column, concatenated",
			[]string{"ssql from " + csv, "ssql include name age salary", "ssql unpivot -id name -col k"},
			[]string{
				`let s1 = df.clone().filter(col("age").is_not_null())?.select(vec![col("name"), lit("age").alias("k"), col("age").alias("value")])?;`,
				`let s2 = df.clone().filter(col("salary").is_not_null())?.select(vec![col("name"), lit("salary").alias("k"), col("salary").alias("value")])?;`,
				`let df = s1.union(s2)?;`}},
		{"-empty zero coalesces the numeric columns",
			[]string{"ssql from csv " + csv + " -empty zero"},
			[]string{
				`let df = df.with_column("age", coalesce(vec![col("age"), lit(0i64)]))?;`,
				`let df = df.with_column("salary", coalesce(vec![col("salary"), lit(0i64)]))?;`}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			code := rustFromCommands(t, "", c.cmds...)
			body := strings.Join(rustFuncBody(code), "\n")
			pos := 0
			for _, w := range c.wants {
				i := strings.Index(body[pos:], w)
				if i < 0 {
					t.Fatalf("missing (after offset %d):\n  %s\nin body:\n%s", pos, w, body)
				}
				pos += i + len(w)
			}
			if strings.Contains(code, "ctx.sql(") {
				t.Errorf("the layer ran as SQL text:\n%s", code)
			}
		})
	}
}

// TestGenerateRustDeadSort pins which sorts the program keeps. A sort
// whose only consumer is an order-free aggregate is left out, as the SQL
// engines leave out the same ORDER BY inside a subquery (the DataFrame
// API keeps a sort it is given: the benchmark window ran 14.4 s with it
// and 5.7 s without, DFC158 §3.6); a sort feeding an arrival-order
// aggregate, a limit, or the output stays.
func TestGenerateRustDeadSort(t *testing.T) {
	csv := rustTestCSV(t)
	cases := []struct {
		name string
		cmds []string
		sort bool // the program contains a .sort(
	}{
		{"sort before count: dead", []string{"ssql from " + csv, "ssql sort age", "ssql group-by dept -count n"}, false},
		{"sort before sum and avg: dead", []string{"ssql from " + csv, "ssql sort -desc salary", "ssql group-by dept -sum salary s -avg salary a"}, false},
		{"window's output order before max: dead", []string{"ssql from " + csv, "ssql window -partition dept -order name -sum salary running", "ssql group-by dept -max running m"}, false},
		{"sort before first: kept", []string{"ssql from " + csv, "ssql sort age", "ssql group-by dept -first name f"}, true},
		{"sort before collect: kept", []string{"ssql from " + csv, "ssql sort age", "ssql group-by dept -collect name ns"}, true},
		{"sort before string-agg: kept", []string{"ssql from " + csv, "ssql sort age", "ssql group-by dept -string-agg name , ns"}, true},
		{"sort with a limit before count: kept", []string{"ssql from " + csv, "ssql sort age", "ssql limit 2", "ssql group-by dept -count n"}, true},
		{"sort at the output: kept", []string{"ssql from " + csv, "ssql group-by dept -count n", "ssql sort -desc n"}, true},
		{"sort after the aggregate, then include: kept", []string{"ssql from " + csv, "ssql group-by dept -count n", "ssql sort n", "ssql include dept"}, true},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			code := rustFromCommands(t, "", c.cmds...)
			if got := strings.Contains(code, ".sort(vec!["); got != c.sort {
				t.Errorf("sort present = %v, want %v:\n%s", got, c.sort, code)
			}
		})
	}
}

// rustTestCSV writes a small CSV the translator can read the header of
// (a star projection on DataFusion needs the columns known).
func rustTestCSV(t *testing.T) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), "e.csv")
	if err := os.WriteFile(path, []byte("name,age,dept,salary,status\nann,30,eng,100,active\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

// TestGenerateRustUnion pins the set-operation layer: every side bound,
// projected to the pipeline's columns, combined with the set form.
func TestGenerateRustUnion(t *testing.T) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	must := func(f lib.CodeFragment) {
		if err := enc.Encode(f); err != nil {
			t.Fatal(err)
		}
	}
	must(lib.CodeFragment{Type: "stmt", Command: "ssql from e.csv"})
	must(lib.CodeFragment{Type: "func", FuncName: "unionSource1", FuncBody: []*lib.CodeFragment{{Type: "stmt", Command: "ssql from f.csv"}, {Type: "stmt", Command: "ssql limit 2"}}})
	must(lib.CodeFragment{Type: "stmt", Command: "ssql union -file /dev/fd/63"})
	code, err := assembleRust(&buf, "")
	if err != nil {
		t.Fatal(err)
	}
	body := strings.Join(rustFuncBody(code), "\n")
	for _, w := range []string{
		`let s1 = ctx.read_csv("e.csv", CsvReadOptions::new().has_header(true)).await?;`,
		`let s2 = ctx.read_csv("f.csv", CsvReadOptions::new().has_header(true)).await?;`,
		`let s2 = s2.limit(0, Some(2))?;`,
		`let df = s1.union_distinct(s2)?;`,
	} {
		if !strings.Contains(body, w) {
			t.Errorf("missing %s in:\n%s", w, body)
		}
	}
}

// TestGenerateRustFunc pins -func: the function alone, named.
func TestGenerateRustFunc(t *testing.T) {
	code := rustFromCommands(t, "case_a", "ssql from e.csv", "ssql limit 1")
	if !strings.HasPrefix(code, "pub async fn case_a(ctx: &SessionContext) -> Result<DataFrame> {\n") {
		t.Errorf("unexpected start:\n%s", code)
	}
	if strings.Contains(code, "fn main") || strings.Contains(code, "use datafusion") {
		t.Errorf("-func must emit the function alone:\n%s", code)
	}
}

// TestGenerateRustRuns compiles and runs the codelab pipeline when cargo
// is available (opt-in by toolchain: the first build compiles DataFusion
// and takes minutes; later ones relink). It is the one test that proves
// the rendered program is a program.
func TestGenerateRustRuns(t *testing.T) {
	if testing.Short() {
		t.Skip("compiles a Rust program")
	}
	if _, err := rustCargo(); err != nil {
		t.Skip(err)
	}
	if os.Getenv("SSQL_RUST_LANE") == "" {
		t.Skip("set SSQL_RUST_LANE=1 to compile the generated Rust (minutes on the first build)")
	}
	dir := t.TempDir()
	csv := "name,age,dept,salary,status\nann,30,eng,100,active\nbob,40,eng,200,active\ncid,50,ops,300,left\n"
	if err := os.WriteFile(filepath.Join(dir, "e.csv"), []byte(csv), 0o644); err != nil {
		t.Fatal(err)
	}
	code := rustFromCommands(t, "",
		"ssql from e.csv",
		"ssql where -if status eq active",
		"ssql update -set-expr bonus 'salary * 0.1'",
		"ssql group-by dept -avg salary avg_salary -sum bonus bonus -count n",
		"ssql sort -desc avg_salary",
		"ssql to jsonl")
	crate, bin, err := compileRustSource(code, "")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(crate)
	cmd := exec.Command(bin)
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("run: %v\n%s", err, out)
	}
	got := strings.TrimSpace(string(out))
	want := `{"dept":"eng","avg_salary":150.0,"bonus":30.0,"n":2}`
	if got != want {
		t.Errorf("output\n got %s\nwant %s", got, want)
	}
}

// TestGenerateRustSourceOptions: the Rust lowering reads what DataFusion's
// SQL file table cannot (2026-10-30) — a .tsv with its delimiter and
// extension, a .jsonl with its extension, and a declared schema when a
// type is declared or a column holds an integer past int64: every header
// column (a -columns projection still reads them all), int128 as
// Decimal128(38, 0), a declared decimal read as text and cast after the
// read (the CSV reader truncates extra digits; the cast rounds as ssql
// does). The datafusion dialect of generate sql still refuses all three.
func TestGenerateRustSourceOptions(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) string {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}
	tsv := write("t.tsv", "id\tname\tbig\n1\tAl\t123456789012345678901234\n2\tBo\t5\n")
	jsonl := write("e.jsonl", "{\"id\":1}\n")
	csv := write("z.csv", "id,zip,amt\n1,02134,12.50\n")

	has := func(code string, want ...string) {
		t.Helper()
		for _, w := range want {
			if !strings.Contains(code, w) {
				t.Errorf("generated Rust lacks %q\n%s", w, code)
			}
		}
	}
	has(rustFromCommands(t, "", "ssql from tsv "+tsv),
		`.delimiter(b'\t').file_extension(".tsv").schema(&df_schema)`,
		`Field::new("id", DataType::Int64, true),`,
		`Field::new("big", DataType::Decimal128(38, 0), true),`)
	has(rustFromCommands(t, "", "ssql from jsonl "+jsonl),
		`JsonReadOptions::default().file_extension(".jsonl")`)
	code := rustFromCommands(t, "", "ssql from csv "+csv+" -type zip string -type amt decimal:2 -columns amt")
	has(code,
		`Field::new("id", DataType::Int64, true),`,
		`Field::new("zip", DataType::Utf8, true),`,
		`Field::new("amt", DataType::Utf8, true),`,
		`.with_column("amt", cast(col("amt"), DataType::Decimal128(38, 2)))?;`)
	// No declaration, no wide column: DataFusion infers.
	if code := rustFromCommands(t, "", "ssql from csv "+csv); strings.Contains(code, "Schema::new") {
		t.Errorf("an undeclared CSV got a schema\n%s", code)
	}
	// The SQL dialect is unchanged.
	for _, cmd := range []string{"ssql from tsv " + tsv, "ssql from csv " + csv + " -type zip string"} {
		var buf bytes.Buffer
		if err := json.NewEncoder(&buf).Encode(lib.CodeFragment{Type: "stmt", Command: cmd}); err != nil {
			t.Fatal(err)
		}
		if _, err := assembleSQLDialect(&buf, dialectDataFusion); err == nil {
			t.Errorf("generate sql -dialect datafusion accepted %q", cmd)
		}
	}
}
